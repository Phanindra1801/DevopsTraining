SELECT CURRENT_ROLE();

CREATE DATABASE IF NOT EXISTS EV_CHARGING_DB;

CREATE SCHEMA IF NOT EXISTS EV_CHARGING_DB.RAW;

USE DATABASE EV_CHARGING_DB;

USE SCHEMA EV_CHARGING_DB.RAW;

SHOW SCHEMAS IN DATABASE EV_CHARGING_DB;

CREATE WAREHOUSE IF NOT EXISTS EV_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE EV_WH;

CREATE TABLE IF NOT EXISTS EV_SESSIONS (
    SESSION_ID NUMBER(10,0),
    SESSION_DATE VARCHAR(20),
    CHARGER_TYPE VARCHAR(100),
    ENERGY_KWH VARCHAR(50),
    RATE_PER_KWH VARCHAR(50),
    CITY VARCHAR(100)
);

CREATE FILE FORMAT IF NOT EXISTS EV_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS EV_STAGE
FILE_FORMAT = EV_CSV_FORMAT;

COPY INTO EV_CHARGING_DB.RAW.EV_SESSIONS
FROM @EV_CHARGING_DB.RAW.EV_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'EV_CHARGING_DB.RAW.EV_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_SESSIONS
FROM EV_CHARGING_DB.RAW.EV_SESSIONS;

SELECT *
FROM EV_CHARGING_DB.RAW.EV_SESSIONS
ORDER BY SESSION_ID;

SELECT
    SESSION_ID,
    COUNT(*) AS SESSION_COUNT
FROM EV_SESSIONS
GROUP BY SESSION_ID
HAVING COUNT(*) > 1;

SELECT
    MIN(TRY_TO_NUMBER(ENERGY_KWH)) AS MIN_ENERGY,
    MAX(TRY_TO_NUMBER(ENERGY_KWH)) AS MAX_ENERGY,
    AVG(TRY_TO_NUMBER(ENERGY_KWH)) AS AVG_ENERGY,
    SUM(TRY_TO_NUMBER(ENERGY_KWH)) AS TOTAL_ENERGY,
    MEDIAN(TRY_TO_NUMBER(ENERGY_KWH)) AS MEDIAN_ENERGY
FROM EV_SESSIONS;

SELECT
    CITY,
    SUM(
        TRY_TO_DECIMAL(ENERGY_KWH, 12, 2) *
        TRY_TO_DECIMAL(RATE_PER_KWH, 12, 2)
    ) AS TOTAL_REVENUE
FROM EV_SESSIONS
WHERE TRY_TO_DECIMAL(ENERGY_KWH, 12, 2) > 0
  AND TRY_TO_DECIMAL(RATE_PER_KWH, 12, 2) > 0
  AND CITY IS NOT NULL
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;