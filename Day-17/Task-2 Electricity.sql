CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID VARCHAR(10),
    CUSTOMER_NAME VARCHAR(100),
    CUSTOMER_TYPE VARCHAR(50),
    CITY VARCHAR(100),
    CONNECTION_TYPE VARCHAR(50),
    EMAIL VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS ELECTRICITY_BILLS (
    BILL_ID VARCHAR(10),
    CUSTOMER_ID VARCHAR(10),
    BILLING_MONTH DATE,
    UNITS_CONSUMED NUMBER(12,2),
    RATE_PER_UNIT NUMBER(10,2),
    SURCHARGE NUMBER(10,2),
    BILL_AMOUNT NUMBER(14,2)
);

CREATE FILE FORMAT IF NOT EXISTS ELECTRICITY_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = FALSE;

CREATE STAGE IF NOT EXISTS ELECTRICITY_STAGE;

LIST @ELECTRICITY_STAGE;

COPY INTO CUSTOMERS
