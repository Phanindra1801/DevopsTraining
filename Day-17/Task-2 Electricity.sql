SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CUSTOMER_TYPE,
    LENGTH(CUSTOMER_TYPE) AS FIELD_LENGTH
FROM CUSTOMERS
WHERE CUSTOMER_ID IN ('C008', 'C013');

SELECT
    CUSTOMER_ID,
    CUSTOMER_TYPE,
    COALESCE(CUSTOMER_TYPE, 'UNKNOWN') AS RESULT
FROM CUSTOMERS
WHERE CUSTOMER_ID IN ('C008', 'C013');

SELECT
    COALESCE('', 'UNKNOWN') AS EMPTY_TEST,
    COALESCE('   ', 'UNKNOWN') AS SPACE_TEST,
    COALESCE(NULL, 'UNKNOWN') AS NULL_TEST;

    SELECT
    TRIM('') AS EMPTY_TEST,
    TRIM('   ') AS SPACE_TEST,
    TRIM(NULL) AS NULL_TEST;

    SELECT
    COALESCE(TRIM(''), 'UNKNOWN') AS EMPTY_TEST,
    COALESCE(TRIM('   '), 'UNKNOWN') AS SPACE_TEST,
    COALESCE(TRIM(NULL), 'UNKNOWN') AS NULL_TEST;

    SELECT
    COALESCE(
        NULLIF(TRIM(''), ''),
        'UNKNOWN'
    ) AS EMPTY_TEST,

    COALESCE(
        NULLIF(TRIM('   '), ''),
        'UNKNOWN'
    ) AS SPACE_TEST,

    COALESCE(
        NULLIF(TRIM(NULL), ''),
        'UNKNOWN'
    ) AS NULL_TEST;

    SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CUSTOMER_TYPE,

    TRIM(CUSTOMER_TYPE) AS TRIMMED_VALUE,

    NULLIF(TRIM(CUSTOMER_TYPE), '') AS NULLIF_RESULT,

    COALESCE(
        NULLIF(TRIM(CUSTOMER_TYPE), ''),
        'UNKNOWN'
    ) AS FINAL_CUSTOMER_TYPE

FROM CUSTOMERS
WHERE CUSTOMER_ID IN ('C008', 'C013');

CREATE OR REPLACE VIEW CLEAN_CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,

    COALESCE(
        NULLIF(TRIM(CUSTOMER_TYPE), ''),
        'UNKNOWN'
    ) AS CUSTOMER_TYPE,

    TRIM(CITY) AS CITY,
    TRIM(CONNECTION_TYPE) AS CONNECTION_TYPE,
    EMAIL

FROM CUSTOMERS;

SELECT *
FROM ELECTRICITY_BILLS
ORDER BY BILL_ID;

SELECT
    B.BILL_ID,
    C.CUSTOMER_NAME,
    C.CITY,
    B.BILLING_MONTH,
    B.UNITS_CONSUMED,
    B.BILL_AMOUNT
FROM ELECTRICITY_BILLS B
JOIN CLEAN_CUSTOMERS C
    ON B.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CITY = 'Chennai';

SELECT
    COUNT(BILL_ID) AS TOTAL_BILLS,
    SUM(UNITS_CONSUMED) AS TOTAL_UNITS,
    SUM(BILL_AMOUNT) AS TOTAL_REVENUE,
    AVG(BILL_AMOUNT) AS AVERAGE_BILL_AMOUNT
FROM ELECTRICITY_BILLS;

SELECT
    C.CONNECTION_TYPE,
    COUNT(B.BILL_ID) AS TOTAL_BILLS,
    SUM(B.UNITS_CONSUMED) AS TOTAL_UNITS,
    SUM(B.BILL_AMOUNT) AS TOTAL_REVENUE
FROM ELECTRICITY_BILLS B
JOIN CLEAN_CUSTOMERS C
    ON B.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY C.CONNECTION_TYPE
ORDER BY TOTAL_REVENUE DESC;

SELECT
    B.BILL_ID,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CUSTOMER_TYPE,
    C.CITY,
    B.BILLING_MONTH,
    B.UNITS_CONSUMED,
    B.RATE_PER_UNIT,
    B.BILL_AMOUNT
FROM ELECTRICITY_BILLS B
INNER JOIN CLEAN_CUSTOMERS C
    ON B.CUSTOMER_ID = C.CUSTOMER_ID;

SELECT
    C.CUSTOMER_TYPE,
    COUNT(B.BILL_ID) AS TOTAL_BILLS,
    SUM(B.UNITS_CONSUMED) AS TOTAL_UNITS,
    SUM(B.BILL_AMOUNT) AS TOTAL_REVENUE,
    AVG(B.BILL_AMOUNT) AS AVERAGE_REVENUE
FROM ELECTRICITY_BILLS B
JOIN CLEAN_CUSTOMERS C
    ON B.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY C.CUSTOMER_TYPE
ORDER BY TOTAL_REVENUE DESC;